/**
 * Builds `build/client/legacy.css` — the fallback stylesheet served to browsers
 * that cannot render the modern Tailwind CSS v4 bundle.
 *
 * Tailwind CSS v4 emits all of its styles inside native CSS cascade layers and
 * relies on modern color syntax (`oklch()`, `color-mix()`). Browsers released
 * before ~2022 drop every rule inside `@layer` (unknown at-rules are discarded
 * along with their contents), which leaves the site completely unstyled, and
 * browsers before ~2023 lose the colors. This script turns the production
 * build's stylesheets into a version older browsers can apply:
 *
 *   1. every `.css` asset emitted by the build is collected,
 *   2. `@layer` blocks are unwrapped in place — the build emits them in layer
 *      order (`properties`, `theme`, `base`, `utilities`), so hoisting them
 *      preserves the cascade the layers expressed,
 *   3. individual transform properties (`translate`, `rotate`, `scale`) are
 *      combined into a single `transform`, which Lightning CSS does not
 *      downlevel but old browsers do not support,
 *   4. Lightning CSS downlevels the result for old browser targets (color
 *      fallbacks, vendor prefixes, logical properties, `:where()` fallbacks,
 *      ...) and minifies it,
 *   5. the sheets are concatenated, wrapped in a feature query, and written
 *      next to the other client assets together with `.br`/`.gz` copies so
 *      adapter-node serves them pre-compressed.
 *
 * `src/app.html` links the generated file. The link is removed by a small
 * inline script when the browser supports `oklch()` and `color-mix()`, and the
 * stylesheet itself is also wrapped in `@supports not (...)`, so modern
 * browsers keep using the untouched Tailwind v4 output even when the script
 * does not run.
 *
 * Run with `bun run build:legacy`; it is part of `bun run build`.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { brotliCompressSync, gzipSync } from "node:zlib";
import { transform } from "lightningcss";
import postcss from "postcss";
import { Declaration, type Container } from "postcss";

/** Browsers the fallback sheet targets: the 2017-era baseline used by the article this approach follows. */
const LEGACY_TARGETS = {
  chrome: 62 << 16,
  firefox: 56 << 16,
  safari: 11 << 16,
  edge: 18 << 16
};

/** Modern features that decide whether a browser can use the Tailwind v4 bundle. */
const MODERN_FEATURES = "(color: oklch(0 0 0)) and (color: color-mix(in srgb, red, blue))";

const BANNER =
  "/* Legacy fallback for browsers without oklch()/color-mix(). Generated by scripts/build-legacy-css.ts. */";

const root = process.cwd();
const clientDir = join(root, "build", "client");
const outputFile = join(clientDir, "legacy.css");

/** Recursively list every stylesheet the build emitted. */
function findStylesheets(directory: string): string[] {
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    if (statSync(path).isDirectory()) return findStylesheets(path);
    if (!entry.endsWith(".css")) return [];
    if (path === outputFile) return [];
    return [path];
  });
}

/**
 * Replaces every `@layer <name> { ... }` block with its contents and drops the
 * bare `@layer a, b;` statements. Deepest blocks are unwrapped first so nested
 * layers hoist into their parent correctly.
 */
function unwrapLayers(container: Container) {
  const layers: postcss.AtRule[] = [];
  container.walkAtRules("layer", (atRule) => {
    layers.push(atRule);
  });

  for (const layer of layers.reverse()) {
    if (!layer.parent) continue;
    if (layer.nodes) {
      for (const child of [...layer.nodes]) layer.parent.insertBefore(layer, child);
    }
    layer.remove();
  }
}

/** Splits a CSS value on top-level whitespace, leaving functions and strings intact. */
function splitValues(value: string): string[] {
  const values: string[] = [];
  let current = "";
  let depth = 0;
  let quote = "";

  for (const char of value.trim()) {
    if (quote) {
      current += char;
      if (char === quote) quote = "";
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
    } else if (char === "(") {
      depth += 1;
    } else if (char === ")") {
      depth -= 1;
    } else if (depth === 0 && /\s/.test(char)) {
      if (current) values.push(current);
      current = "";
      continue;
    }
    current += char;
  }
  if (current) values.push(current);

  return values;
}

/**
 * Rewrites the individual transform properties Tailwind uses (`translate`,
 * `rotate`, `scale`) into one `transform` declaration. The individual
 * properties apply in the order translate → rotate → scale, before `transform`
 * itself, so prepending them to an existing `transform` value is equivalent.
 */
function combineTransforms(container: Container) {
  container.walkRules((rule) => {
    if (!rule.nodes) return;
    const declarations = rule.nodes.filter((node): node is Declaration => node.type === "decl");
    const read = (prop: string) => declarations.find((declaration) => declaration.prop === prop);

    const translate = read("translate");
    const rotate = read("rotate");
    const scale = read("scale");
    if (!translate && !rotate && !scale) return;

    const value = (declaration: Declaration | undefined, name: string, args: string) =>
      declaration && declaration.value.trim() !== "none" ? `${name}(${args})` : undefined;

    const parts = [
      value(translate, "translate", splitValues(translate?.value ?? "").join(", ")),
      value(rotate, "rotate", rotate?.value.trim() ?? ""),
      value(scale, "scale", splitValues(scale?.value ?? "").join(", "))
    ].filter((part): part is string => Boolean(part));

    const existing = read("transform");
    for (const declaration of [translate, rotate, scale]) declaration?.remove();
    if (parts.length === 0) return;

    const combined = [parts.join(" "), existing?.value.trim()].filter(Boolean).join(" ");
    if (existing) existing.value = combined;
    else rule.prepend(new Declaration({ prop: "transform", value: combined }));
  });
}

function toLegacyCss(file: string, css: string): string {
  const parsed = postcss.parse(css, { from: file });
  unwrapLayers(parsed);
  combineTransforms(parsed);

  const result = transform({
    filename: file,
    code: Buffer.from(parsed.toString()),
    minify: true,
    errorRecovery: true,
    targets: LEGACY_TARGETS
  });

  for (const warning of result.warnings) {
    console.warn(`[legacy-css] ${relative(root, file)}: ${warning.message}`);
  }

  return result.code.toString();
}

if (!existsSync(clientDir)) {
  console.error("[legacy-css] build/client does not exist - run `bun run build` (which runs this script) instead.");
  process.exit(1);
}

const stylesheets = findStylesheets(clientDir);
if (stylesheets.length === 0) {
  console.error("[legacy-css] no stylesheets found under build/client.");
  process.exit(1);
}

// The global Tailwind sheet loads first on every page and must come first here
// too, so page/component rules keep winning when both set the same property.
const order = (file: string) => (readFileSync(file, "utf8").includes("@layer theme") ? 0 : 1);
stylesheets.sort((a, b) => order(a) - order(b) || a.localeCompare(b));

const sheet = stylesheets.map((file) => toLegacyCss(file, readFileSync(file, "utf8"))).join("\n");
const output = `${BANNER}\n@supports not (${MODERN_FEATURES}){${sheet}}\n`;

writeFileSync(outputFile, output);
writeFileSync(`${outputFile}.br`, brotliCompressSync(output));
writeFileSync(`${outputFile}.gz`, gzipSync(output));

const sources = stylesheets.map((file) => relative(clientDir, file).split(sep).join("/")).join(", ");
console.log(
  `[legacy-css] wrote ${relative(root, outputFile)} (${(output.length / 1024).toFixed(1)} kB) from: ${sources}`
);
