/**
 * Builds the stylesheet served to browsers that cannot run the Tailwind CSS v4
 * bundle (see docs/legacy-browser-support.md).
 *
 * 1. Tailwind CSS v3 compiles `scripts/legacy/legacy.css`, with the theme
 *    mirrored from `src/app.css` by `scripts/legacy/tailwind.config.ts`. v3
 *    output has no cascade layers, `oklch()`, `color-mix()` or `@property`.
 * 2. Lightning CSS downlevels the result for old browsers (static color
 *    syntax, vendor prefixes, `inset`, ...).
 * 3. Production builds also append the scoped component stylesheets that Vite
 *    emitted, downleveled the same way, so component styles still apply.
 *
 * `bun run build:legacy` writes `build/client/legacy.css` (plus `.br`/`.gz`
 * copies). The dev server calls `buildLegacyCss` directly.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, gzipSync } from "node:zlib";
import { transform } from "lightningcss";
import postcss, { Declaration, type Container } from "postcss";
import tailwind from "tailwindcss-v3";
import { createLegacyConfig } from "./legacy/tailwind.config";
import { parseColor, readCustomProperties } from "./legacy/theme";

/** Browsers the output must run in: the earliest versions with CSS custom properties. */
const LEGACY_TARGETS = {
  chrome: 49 << 16,
  firefox: 52 << 16,
  safari: 10 << 16,
  edge: 15 << 16
};

const INPUT = fileURLToPath(new URL("./legacy/legacy.css", import.meta.url));
const THEME_MARKER = "/* @theme-vars */";
const BANNER =
  "/* Legacy stylesheet for browsers without Tailwind CSS v4 support. Generated by scripts/build-legacy-css.ts. */";

/** `:root` and `.dark` custom properties from src/app.css, with RGB triplets for every color. */
function themeBlock(rootDir: string): string {
  const appCss = readFileSync(join(rootDir, "src", "app.css"), "utf8");
  const root = readCustomProperties(appCss, /:root\s*\{([\s\S]*?)\n\}/);
  const dark = readCustomProperties(appCss, /\.dark\s*\{([\s\S]*?)\n\}/);

  const declare = (properties: Record<string, string>) =>
    Object.entries(properties).flatMap(([name, value]) => {
      const color = parseColor(value);
      return color ? [`  --${name}: ${color.hex};`, `  --${name}-rgb: ${color.rgb};`] : [`  --${name}: ${value};`];
    });

  const background = parseColor(root.background ?? "");
  const foreground = parseColor(root.foreground ?? "");

  return [
    ":root {",
    ...declare(root),
    "}",
    ".dark {",
    ...declare(dark),
    "}",
    // Literal colors for browsers without custom properties. The `var()` rules
    // that follow the marker take over wherever custom properties work.
    "body {",
    `  background-color: ${background?.hex ?? "#fff"};`,
    `  color: ${foreground?.hex ?? "#000"};`,
    "}"
  ].join("\n");
}

async function compileTailwindV3(rootDir: string): Promise<string> {
  const input = readFileSync(INPUT, "utf8").replace(THEME_MARKER, themeBlock(rootDir));
  const result = await postcss([tailwind(createLegacyConfig(rootDir))]).process(input, { from: INPUT });
  return result.css;
}

function downlevel(file: string, css: string): string {
  const result = transform({
    filename: file,
    code: Buffer.from(css),
    minify: true,
    errorRecovery: true,
    targets: LEGACY_TARGETS
  });

  for (const warning of result.warnings) {
    console.warn(`[legacy-css] ${file}: ${warning.message}`);
  }

  return result.code.toString();
}

/** Recursively lists the emitted stylesheets, skipping the legacy output itself. */
function findStylesheets(directory: string, skip: string): string[] {
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    if (statSync(path).isDirectory()) return findStylesheets(path, skip);
    if (!entry.endsWith(".css") || path === skip) return [];
    return [path];
  });
}

/**
 * Replaces every `@layer <name> { ... }` block with its contents and drops the
 * bare `@layer a, b;` statements. Deepest blocks are unwrapped first.
 */
function unwrapLayers(container: Container) {
  const layers: postcss.AtRule[] = [];
  container.walkAtRules("layer", (atRule) => {
    layers.push(atRule);
  });

  for (const layer of layers.reverse()) {
    if (!layer.parent) continue;
    if (layer.nodes) {
      for (const child of [...layer.nodes]) layer.parent.insertBefore(layer, child);
    }
    layer.remove();
  }
}

/** Splits a CSS value on top-level whitespace, leaving functions and strings intact. */
function splitValues(value: string): string[] {
  const values: string[] = [];
  let current = "";
  let depth = 0;
  let quote = "";

  for (const char of value.trim()) {
    if (quote) {
      current += char;
      if (char === quote) quote = "";
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
    } else if (char === "(") {
      depth += 1;
    } else if (char === ")") {
      depth -= 1;
    } else if (depth === 0 && /\s/.test(char)) {
      if (current) values.push(current);
      current = "";
      continue;
    }
    current += char;
  }
  if (current) values.push(current);

  return values;
}

/**
 * Combines the individual transform properties (`translate`, `rotate`, `scale`)
 * into one `transform`, which old browsers understand. The individual properties
 * apply before `transform`, so prepending them to an existing value is equivalent.
 */
function combineTransforms(container: Container) {
  container.walkRules((rule) => {
    if (!rule.nodes) return;
    const declarations = rule.nodes.filter((node): node is Declaration => node.type === "decl");
    const read = (prop: string) => declarations.find((declaration) => declaration.prop === prop);

    const translate = read("translate");
    const rotate = read("rotate");
    const scale = read("scale");
    if (!translate && !rotate && !scale) return;

    const value = (declaration: Declaration | undefined, name: string, args: string) =>
      declaration && declaration.value.trim() !== "none" ? `${name}(${args})` : undefined;

    const parts = [
      value(translate, "translate", splitValues(translate?.value ?? "").join(", ")),
      value(rotate, "rotate", rotate?.value.trim() ?? ""),
      value(scale, "scale", splitValues(scale?.value ?? "").join(", "))
    ].filter((part): part is string => Boolean(part));

    const existing = read("transform");
    for (const declaration of [translate, rotate, scale]) declaration?.remove();
    if (parts.length === 0) return;

    const combined = [parts.join(" "), existing?.value.trim()].filter(Boolean).join(" ");
    if (existing) existing.value = combined;
    else rule.prepend(new Declaration({ prop: "transform", value: combined }));
  });
}

/** Scoped component styles from the production build, downleveled. */
function componentStylesheets(clientDir: string): string[] {
  const legacyFile = join(clientDir, "legacy.css");
  return findStylesheets(clientDir, legacyFile)
    .filter((file) => !readFileSync(file, "utf8").includes("@layer theme"))
    .sort((a, b) => a.localeCompare(b))
    .map((file) => {
      const parsed = postcss.parse(readFileSync(file, "utf8"), { from: file });
      unwrapLayers(parsed);
      combineTransforms(parsed);
      return downlevel(relative(clientDir, file), parsed.toString());
    });
}

/**
 * Returns the legacy stylesheet. Pass `clientDir` (a production build) to also
 * include the downleveled component styles.
 */
export async function buildLegacyCss(options: { rootDir: string; clientDir?: string }): Promise<string> {
  const global = downlevel("legacy.css", await compileTailwindV3(options.rootDir));
  const components = options.clientDir ? componentStylesheets(options.clientDir) : [];
  return `${BANNER}\n${[global, ...components].join("\n")}\n`;
}

if (import.meta.main) {
  const rootDir = process.cwd();
  const clientDir = join(rootDir, "build", "client");

  if (!existsSync(clientDir)) {
    console.error(
      "[legacy-css] build/client does not exist - run `bun run build`, which runs this script after vite build."
    );
    process.exit(1);
  }

  const css = await buildLegacyCss({ rootDir, clientDir });
  const output = join(clientDir, "legacy.css");
  writeFileSync(output, css);
  writeFileSync(`${output}.br`, brotliCompressSync(css));
  writeFileSync(`${output}.gz`, gzipSync(css));

  console.log(`[legacy-css] wrote ${relative(rootDir, output)} (${(css.length / 1024).toFixed(1)} kB)`);
}
